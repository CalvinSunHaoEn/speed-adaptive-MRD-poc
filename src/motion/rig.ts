/**
 * Map a joint's sample points onto a different cycle window, keeping the
 * padding holds at 0 and 1. The curve is unchanged — only how long it takes.
 */
export function retime(times: readonly number[], start: number, end: number): number[] {
  const first = times[1]
  const span = times[times.length - 2] - first
  return times.map((t, i) =>
    i === 0 ? 0 : i === times.length - 1 ? 1 : start + ((t - first) / span) * (end - start),
  )
}
